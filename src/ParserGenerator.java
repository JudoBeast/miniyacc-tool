import java.util.*;

/** Emits a standalone Java parser (GeneratedParser.java) from the SLR(1) tables. */
public class ParserGenerator {
    public static String generate(SlrEngine e) {
        List<String> cols = e.columns(), gcols = e.gotoColumns();
        int n = e.states.size();
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by MiniYACC Tool: SLR(1) shift-reduce parser\nimport java.util.*;\n\npublic class GeneratedParser {\n");
        sb.append("    static final String[] TERMS = ").append(arr(cols)).append(";\n");
        sb.append("    static final String[] NONTERMS = ").append(arr(gcols)).append(";\n");
        List<String> lhs = new ArrayList<>(); List<String> len = new ArrayList<>(); List<String> txt = new ArrayList<>();
        for (SlrEngine.Prod p : e.prods) { lhs.add(p.lhs); len.add(String.valueOf(p.rhs.size())); txt.add(p.toString().replace("→", "->")); }
        sb.append("    static final String[] LHS = ").append(arr(lhs)).append(";\n");
        sb.append("    static final int[] LEN = {").append(String.join(", ", len)).append("};\n");
        sb.append("    static final String[] PROD = ").append(arr(txt)).append(";\n");
        sb.append("    static final String[][] ACTION = {\n");
        for (int i = 0; i < n; i++) {
            List<String> row = new ArrayList<>(); for (String c : cols) row.add(e.action.get(i).getOrDefault(c, ""));
            sb.append("        ").append(arr(row)).append(i < n - 1 ? ",\n" : "\n");
        }
        sb.append("    };\n    static final int[][] GOTO = {\n");
        for (int i = 0; i < n; i++) {
            List<String> row = new ArrayList<>(); for (String g : gcols) row.add(String.valueOf(e.gotoT.get(i).getOrDefault(g, -1)));
            sb.append("        {").append(String.join(", ", row)).append("}").append(i < n - 1 ? ",\n" : "\n");
        }
        sb.append("    };\n\n");
        sb.append("    static int idx(String[] a, String s) { for (int i = 0; i < a.length; i++) if (a[i].equals(s)) return i; return -1; }\n\n");
        sb.append("    public static boolean parse(List<String> tokens) {\n");
        sb.append("        List<String> in = new ArrayList<>(tokens); in.add(\"$\");\n");
        sb.append("        Deque<Integer> st = new ArrayDeque<>(); st.push(0); int pos = 0;\n");
        sb.append("        while (true) {\n");
        sb.append("            int c = idx(TERMS, in.get(pos));\n");
        sb.append("            String act = c < 0 ? \"\" : ACTION[st.peek()][c];\n");
        sb.append("            if (act.isEmpty()) { System.out.println(\"syntax error at token \" + (pos + 1) + \" (\" + in.get(pos) + \")\"); return false; }\n");
        sb.append("            if (act.equals(\"acc\")) return true;\n");
        sb.append("            if (act.charAt(0) == 's') { st.push(Integer.parseInt(act.substring(1))); pos++; }\n");
        sb.append("            else { int p = Integer.parseInt(act.substring(1)); for (int i = 0; i < LEN[p]; i++) st.pop();\n");
        sb.append("                   System.out.println(\"reduce \" + PROD[p]); st.push(GOTO[st.peek()][idx(NONTERMS, LHS[p])]); }\n");
        sb.append("        }\n    }\n\n");
        sb.append("    public static void main(String[] args) {\n");
        sb.append("        String line = args.length > 0 ? String.join(\" \", args) : new Scanner(System.in).nextLine();\n");
        sb.append("        List<String> toks = new ArrayList<>(); for (String t : line.trim().split(\"\\\\s+\")) if (!t.isEmpty()) toks.add(t);\n");
        sb.append("        System.out.println(parse(toks) ? \"accepted\" : \"rejected\");\n    }\n}\n");
        return sb.toString();
    }
    private static String arr(List<String> l) {
        StringBuilder sb = new StringBuilder("{");
        for (int i = 0; i < l.size(); i++) sb.append(i > 0 ? ", " : "").append('"').append(l.get(i).replace("\\", "\\\\").replace("\"", "\\\"")).append('"');
        return sb.append("}").toString();
    }
}
